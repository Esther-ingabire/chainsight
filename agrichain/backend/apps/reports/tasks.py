def _generate_cold_chain_report(period_start, period_end, ExportReportView):
    from apps.iot.models import IoTReading

    report = Report.objects.create(
        report_type=Report.ReportType.COLD_CHAIN_COMPLIANCE,
        title=f'Cold Chain Compliance Report — {period_start} to {period_end}',
        format=Report.Format.PDF,
        status=Report.Status.GENERATING,
        period_start=period_start, period_end=period_end,
        generated_by_job=True,
    )
    try:
        readings = IoTReading.objects.filter(
            timestamp__date__gte=period_start, timestamp__date__lte=period_end,
        )
        facility_rows = list(
            readings.values('facility__name', 'facility__cooperative__district')
            .annotate(
                total=Count('id'),
                breaches=Count('id', filter=Q(is_temperature_breach=True) | Q(is_humidity_breach=True)),
            )
            .order_by('facility__name')
        )
        headers = ['Facility', 'District', 'Readings', 'Breaches', 'Compliance (%)']
        rows = []
        for r in facility_rows:
            total = r['total']
            breaches = r['breaches']
            compliance = round((1 - breaches / total) * 100, 1) if total else 100.0
            rows.append([
                r['facility__name'], r['facility__cooperative__district'] or '—',
                total, breaches, compliance,
            ])
        pdf_bytes = ExportReportView._build_pdf_bytes(
            report.title, headers, rows, 'Scheduled Job', 'System',
        )
        _save_report_file(report, pdf_bytes, 'pdf')
    except Exception as e:
        report.status = Report.Status.FAILED
        report.error_message = str(e)
        report.save()
        raise
